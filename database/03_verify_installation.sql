    RAISE_APPLICATION_ERROR(-20032, 'Expected 8 blood groups and 27 compatibility pairs; found ' || groups_count || ' and ' || pairs_count || '.');
  END IF;
  DBMS_OUTPUT.PUT_LINE('PASS: 8 blood groups and 27 compatibility pairs are present.');
END;
