  groups_count NUMBER;
  pairs_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO groups_count FROM BLOOD_GROUPS;
  SELECT COUNT(*) INTO pairs_count FROM BLOOD_COMPATIBILITY;
