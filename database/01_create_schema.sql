CREATE TABLE DONOR_INVITATIONS (
    INVITATION_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    REQUEST_ID NUMBER NOT NULL,
    DONOR_ID NUMBER NOT NULL,
    INVITED_BY_USER_ID NUMBER NOT NULL,
    INVITATION_STATUS VARCHAR2(20) DEFAULT 'SENT' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_DI_REQUEST FOREIGN KEY (REQUEST_ID) REFERENCES BLOOD_REQUESTS(REQUEST_ID),
    CONSTRAINT FK_DI_DONOR FOREIGN KEY (DONOR_ID) REFERENCES DONORS(DONOR_ID),
    CONSTRAINT FK_DI_REQUESTER FOREIGN KEY (INVITED_BY_USER_ID) REFERENCES USERS(USER_ID),
