CREATE TABLE LOCATIONS (
    LOCATION_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    ADDRESS_LINE VARCHAR2(300),
    CITY VARCHAR2(100) NOT NULL,
    DISTRICT VARCHAR2(100),
    STATE VARCHAR2(100) NOT NULL,
    PINCODE VARCHAR2(10),
    LATITUDE NUMBER(10,7),
    LONGITUDE NUMBER(10,7),
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE DONORS (
    DONOR_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    USER_ID NUMBER NOT NULL UNIQUE,
    BLOOD_GROUP_ID NUMBER(3) NOT NULL,
    LOCATION_ID NUMBER,
    DATE_OF_BIRTH DATE NOT NULL,
    AVAILABILITY_STATUS VARCHAR2(20) DEFAULT 'AVAILABLE' NOT NULL,
    LAST_DONATION_DATE DATE,
    CONTACT_CONSENT CHAR(1) DEFAULT 'N' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_DONORS_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID),
    CONSTRAINT FK_DONORS_GROUP FOREIGN KEY (BLOOD_GROUP_ID) REFERENCES BLOOD_GROUPS(BLOOD_GROUP_ID),
    CONSTRAINT FK_DONORS_LOCATION FOREIGN KEY (LOCATION_ID) REFERENCES LOCATIONS(LOCATION_ID),
    CONSTRAINT CK_DONOR_AVAILABILITY CHECK (AVAILABILITY_STATUS IN ('AVAILABLE','UNAVAILABLE')),
    CONSTRAINT CK_DONOR_CONSENT CHECK (CONTACT_CONSENT IN ('Y','N'))
);

CREATE TABLE REQUESTERS (
    REQUESTER_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    USER_ID NUMBER NOT NULL UNIQUE,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_REQUESTERS_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID)
);

CREATE TABLE BLOOD_REQUESTS (
    REQUEST_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    REQUESTER_USER_ID NUMBER NOT NULL,
    BLOOD_GROUP_ID NUMBER(3) NOT NULL,
    LOCATION_ID NUMBER,
    HOSPITAL_NAME VARCHAR2(200) NOT NULL,
    HOSPITAL_ADDRESS VARCHAR2(500) NOT NULL,
    UNITS_REQUIRED NUMBER(2) NOT NULL,
    URGENCY VARCHAR2(20) DEFAULT 'NORMAL' NOT NULL,
    REQUIRED_BY TIMESTAMP NOT NULL,
    REQUEST_DETAILS VARCHAR2(2000),
    REQUEST_STATUS VARCHAR2(20) DEFAULT 'OPEN' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_BR_REQUESTER FOREIGN KEY (REQUESTER_USER_ID) REFERENCES USERS(USER_ID),
    CONSTRAINT FK_BR_GROUP FOREIGN KEY (BLOOD_GROUP_ID) REFERENCES BLOOD_GROUPS(BLOOD_GROUP_ID),
    CONSTRAINT FK_BR_LOCATION FOREIGN KEY (LOCATION_ID) REFERENCES LOCATIONS(LOCATION_ID),
    CONSTRAINT CK_BR_UNITS CHECK (UNITS_REQUIRED BETWEEN 1 AND 10),
    CONSTRAINT CK_BR_URGENCY CHECK (URGENCY IN ('NORMAL','URGENT','CRITICAL')),
    CONSTRAINT CK_BR_STATUS CHECK (REQUEST_STATUS IN ('OPEN','MATCHED','FULFILLED','CANCELLED','CLOSED'))
);

CREATE TABLE DONOR_RESPONSES (
    RESPONSE_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    REQUEST_ID NUMBER NOT NULL,
    DONOR_ID NUMBER NOT NULL,
    RESPONSE_STATUS VARCHAR2(20) NOT NULL,
    RESPONDED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    RESPONSE_NOTES VARCHAR2(1000),
    CONSTRAINT FK_DR_REQUEST FOREIGN KEY (REQUEST_ID) REFERENCES BLOOD_REQUESTS(REQUEST_ID),
    CONSTRAINT FK_DR_DONOR FOREIGN KEY (DONOR_ID) REFERENCES DONORS(DONOR_ID),
    CONSTRAINT UQ_DR_REQUEST_DONOR UNIQUE (REQUEST_ID, DONOR_ID),
    CONSTRAINT CK_DR_STATUS CHECK (RESPONSE_STATUS IN ('PENDING','ACCEPTED','REJECTED'))
);

CREATE TABLE DONATION_HISTORY (
    DONATION_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    DONOR_ID NUMBER NOT NULL,
    REQUEST_ID NUMBER,
    DONATION_DATE DATE NOT NULL,
    UNITS_DONATED NUMBER(2) NOT NULL,
    VERIFICATION_STATUS VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
    HOSPITAL_NAME VARCHAR2(200) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_DH_DONOR FOREIGN KEY (DONOR_ID) REFERENCES DONORS(DONOR_ID),
    CONSTRAINT FK_DH_REQUEST FOREIGN KEY (REQUEST_ID) REFERENCES BLOOD_REQUESTS(REQUEST_ID),
    CONSTRAINT CK_DH_UNITS CHECK (UNITS_DONATED BETWEEN 1 AND 10),
    CONSTRAINT CK_DH_STATUS CHECK (VERIFICATION_STATUS IN ('PENDING','VERIFIED','REJECTED'))
);

CREATE TABLE NOTIFICATIONS (
    NOTIFICATION_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    USER_ID NUMBER NOT NULL,
    TITLE VARCHAR2(160) NOT NULL,
    MESSAGE VARCHAR2(1000) NOT NULL,
    NOTIFICATION_TYPE VARCHAR2(40),
    IS_READ CHAR(1) DEFAULT 'N' NOT NULL,
    RELATED_REQUEST_ID NUMBER,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_NOTIF_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID),
    CONSTRAINT FK_NOTIF_REQUEST FOREIGN KEY (RELATED_REQUEST_ID) REFERENCES BLOOD_REQUESTS(REQUEST_ID),
    CONSTRAINT CK_NOTIF_READ CHECK (IS_READ IN ('Y','N'))
);

CREATE INDEX IX_DONORS_GROUP_STATUS ON DONORS(BLOOD_GROUP_ID, AVAILABILITY_STATUS);
CREATE INDEX IX_DONORS_LOCATION ON DONORS(LOCATION_ID);
CREATE INDEX IX_REQUESTS_STATUS_URGENCY ON BLOOD_REQUESTS(REQUEST_STATUS, URGENCY, CREATED_AT);
CREATE INDEX IX_REQUESTS_REQUESTER ON BLOOD_REQUESTS(REQUESTER_USER_ID, CREATED_AT);
CREATE INDEX IX_NOTIFICATIONS_USER ON NOTIFICATIONS(USER_ID, IS_READ, CREATED_AT);

COMMIT;

