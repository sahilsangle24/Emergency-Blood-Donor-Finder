SET SERVEROUTPUT ON
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
DECLARE
  n NUMBER;
BEGIN
  SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME = 'DONOR_INVITATIONS';
  IF n = 0 THEN
    EXECUTE IMMEDIATE q'~CREATE TABLE DONOR_INVITATIONS (
      INVITATION_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
      REQUEST_ID NUMBER NOT NULL,
      DONOR_ID NUMBER NOT NULL,
      INVITED_BY_USER_ID NUMBER NOT NULL,
      INVITATION_STATUS VARCHAR2(20) DEFAULT 'SENT' NOT NULL,
      CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
      CONSTRAINT FK_DI_REQUEST FOREIGN KEY (REQUEST_ID) REFERENCES BLOOD_REQUESTS(REQUEST_ID),
      CONSTRAINT FK_DI_DONOR FOREIGN KEY (DONOR_ID) REFERENCES DONORS(DONOR_ID),
      CONSTRAINT FK_DI_REQUESTER FOREIGN KEY (INVITED_BY_USER_ID) REFERENCES USERS(USER_ID),
      CONSTRAINT UQ_DI_REQUEST_DONOR UNIQUE (REQUEST_ID,DONOR_ID),
      CONSTRAINT CK_DI_STATUS CHECK (INVITATION_STATUS IN ('SENT','ACCEPTED','DECLINED'))
    )~';
    DBMS_OUTPUT.PUT_LINE('Created DONOR_INVITATIONS');
  ELSE
    DBMS_OUTPUT.PUT_LINE('DONOR_INVITATIONS already exists; no change made');
  END IF;
END;
/
DECLARE n NUMBER; BEGIN SELECT COUNT(*) INTO n FROM USER_INDEXES WHERE INDEX_NAME='IX_DI_DONOR_STATUS'; IF n=0 THEN EXECUTE IMMEDIATE 'CREATE INDEX IX_DI_DONOR_STATUS ON DONOR_INVITATIONS(DONOR_ID, INVITATION_STATUS)'; END IF; END;
