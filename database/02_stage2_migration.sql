DECLARE n NUMBER; BEGIN SELECT COUNT(*) INTO n FROM USER_INDEXES WHERE INDEX_NAME='IX_DI_REQUEST_STATUS'; IF n=0 THEN EXECUTE IMMEDIATE 'CREATE INDEX IX_DI_REQUEST_STATUS ON DONOR_INVITATIONS(REQUEST_ID, INVITATION_STATUS)'; END IF; END;
