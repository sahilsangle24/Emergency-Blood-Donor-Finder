-- Emergency Blood Donor Finder: idempotent Oracle 26ai Free installation/upgrade
-- Run as EBDF_APP while connected to service FREEPDB1.
-- Safe to re-run: existing tables are preserved; missing tables/indexes are created;
-- reference data and settings are MERGEd. No existing application data is deleted.
-- Identity columns own their backing sequences; separate sequences are not required.
SET DEFINE OFF
SET SERVEROUTPUT ON
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

-- Create USERS only when it is not already present.
DECLARE
  n NUMBER;
BEGIN
  SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME = 'USERS';
  IF n = 0 THEN
    EXECUTE IMMEDIATE q'~CREATE TABLE USERS (
    USER_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    FULL_NAME VARCHAR2(120) NOT NULL,
    EMAIL VARCHAR2(254) NOT NULL,
    PHONE VARCHAR2(15) NOT NULL,
    PASSWORD_HASH VARCHAR2(100) NOT NULL,
    ROLE VARCHAR2(20) DEFAULT 'REQUESTER' NOT NULL,
    ACCOUNT_STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UQ_USERS_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_USERS_ROLE CHECK (ROLE IN ('DONOR','REQUESTER','ADMIN')),
    CONSTRAINT CK_USERS_STATUS CHECK (ACCOUNT_STATUS IN ('ACTIVE','INACTIVE','SUSPENDED')),
    CONSTRAINT CK_USERS_PHONE CHECK (REGEXP_LIKE(PHONE, '^[0-9]{10,15}$'))
)~';
    DBMS_OUTPUT.PUT_LINE('Created USERS');
  ELSE
    DBMS_OUTPUT.PUT_LINE('Preserved existing USERS');
  END IF;
END;
