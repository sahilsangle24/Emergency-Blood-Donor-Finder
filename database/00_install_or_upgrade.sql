-- Blood groups: IDs 4-11 are retained for compatibility with the React forms.
MERGE INTO BLOOD_GROUPS t
USING (
  SELECT 4 id, 'A+' code FROM DUAL UNION ALL SELECT 5, 'A-' FROM DUAL UNION ALL
  SELECT 6, 'B+' FROM DUAL UNION ALL SELECT 7, 'B-' FROM DUAL UNION ALL
  SELECT 8, 'AB+' FROM DUAL UNION ALL SELECT 9, 'AB-' FROM DUAL UNION ALL
  SELECT 10, 'O+' FROM DUAL UNION ALL SELECT 11, 'O-' FROM DUAL
) s ON (t.BLOOD_GROUP_ID=s.id)
WHEN MATCHED THEN UPDATE SET t.BLOOD_GROUP_CODE=s.code
WHEN NOT MATCHED THEN INSERT (BLOOD_GROUP_ID,BLOOD_GROUP_CODE) VALUES (s.id,s.code);

-- Standard red-cell donor -> recipient compatibility. These records are coordination hints only.
MERGE INTO BLOOD_COMPATIBILITY t
USING (
  SELECT 11 donor_id,11 recipient_id FROM DUAL UNION ALL SELECT 11,10 FROM DUAL UNION ALL SELECT 10,10 FROM DUAL UNION ALL
  SELECT 11,5 FROM DUAL UNION ALL SELECT 5,5 FROM DUAL UNION ALL SELECT 11,7 FROM DUAL UNION ALL SELECT 7,7 FROM DUAL UNION ALL
  SELECT 11,9 FROM DUAL UNION ALL SELECT 5,9 FROM DUAL UNION ALL SELECT 7,9 FROM DUAL UNION ALL SELECT 9,9 FROM DUAL UNION ALL
  SELECT 11,4 FROM DUAL UNION ALL SELECT 10,4 FROM DUAL UNION ALL SELECT 5,4 FROM DUAL UNION ALL SELECT 4,4 FROM DUAL UNION ALL
  SELECT 11,6 FROM DUAL UNION ALL SELECT 10,6 FROM DUAL UNION ALL SELECT 7,6 FROM DUAL UNION ALL SELECT 6,6 FROM DUAL UNION ALL
  SELECT 11,8 FROM DUAL UNION ALL SELECT 10,8 FROM DUAL UNION ALL SELECT 5,8 FROM DUAL UNION ALL SELECT 4,8 FROM DUAL UNION ALL
  SELECT 9,8 FROM DUAL UNION ALL SELECT 7,8 FROM DUAL UNION ALL SELECT 6,8 FROM DUAL UNION ALL SELECT 8,8 FROM DUAL
) s ON (t.DONOR_GROUP_ID=s.donor_id AND t.RECIPIENT_GROUP_ID=s.recipient_id)
WHEN NOT MATCHED THEN INSERT (DONOR_GROUP_ID,RECIPIENT_GROUP_ID) VALUES (s.donor_id,s.recipient_id);

-- Platform settings are inserted only if missing; administrator changes are preserved.
MERGE INTO APP_SETTINGS t USING (
  SELECT 'platformName' k,'LifeLink' v FROM DUAL UNION ALL
  SELECT 'supportEmail','support@lifelink.com' FROM DUAL UNION ALL
  SELECT 'allowRegistration','true' FROM DUAL UNION ALL
  SELECT 'allowBloodRequests','true' FROM DUAL UNION ALL
  SELECT 'emergencyAlerts','true' FROM DUAL
) s ON (t.SETTING_KEY=s.k)
WHEN NOT MATCHED THEN INSERT (SETTING_KEY,SETTING_VALUE,UPDATED_AT) VALUES (s.k,s.v,SYSTIMESTAMP);

